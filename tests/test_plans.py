"""
The public site prints pricing.py's numbers and nothing else (2026-09-18).

web/src/content/pricing.json is GENERATED by `python -m src.pricing
export` and committed; the /pricing and /models pages import it. This
test is the wire between the two: change a plan, a markup, a band or a
rate card without re-exporting and CI fails here, naming the drift.
"""

import json
from pathlib import Path

from src import pricing

CATALOG = Path(__file__).resolve().parent.parent / pricing.CATALOG_PATH


def test_the_committed_catalog_is_what_pricing_py_says():
    committed = json.loads(CATALOG.read_text())
    live = json.loads(json.dumps(pricing.public_catalog()))   # the same JSON round-trip
    assert committed == live, (
        "web/src/content/pricing.json is stale -- run `venv/bin/python -m src.pricing export` "
        "and commit the result")


def test_the_catalog_prices_every_plan_at_the_published_peg():
    catalog = pricing.public_catalog()
    assert catalog["markup"] == pricing.MARKUP == "2.4"
    assert catalog["credit_cents"] == 1
    for plan in catalog["plans"]:
        assert plan["credits"] == plan["monthly_usd"] * 100
        assert plan["tier"] in catalog["tiers"]
    names = {m["name"] for m in catalog["models"]}
    assert {"LTX 2.3", "Runway Gen-4 Turbo", "Kling 3 Turbo Pro", "Seedance 2.0", "Veo 3"} <= names
    for m in catalog["models"]:
        # every advertised clip is priced by the same estimators the Queue uses
        assert m["credits"] >= pricing.CREDIT_FLOOR
        assert m["tier"] in catalog["tiers"]


def test_every_advertised_model_is_a_renderable_one():
    from src import providers
    for provider, model, _name, _blurb in pricing.CATALOG_MODELS:
        choice = providers.check_render_choice(provider, model, None, None)
        assert choice["model"] == model
