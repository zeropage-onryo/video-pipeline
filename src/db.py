def table_exists(conn: psycopg.Connection, table: str) -> bool:
    """Whether `table` resolves on the connection's search_path -- which
    is what makes a per-test schema and the real `public` look alike."""
    row = conn.execute("SELECT to_regclass(%s)", (table,)).fetchone()
    return row is not None and row[0] is not None


def columns(conn: psycopg.Connection, table: str) -> set[str]:
    """The column names of `table` in the current schema. What
    `PRAGMA table_info` was for."""
    rows = conn.execute(
        """
        SELECT column_name FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = %s
        """,
        (table,),
    ).fetchall()
    return {r["column_name"] for r in rows}


def _ensure_accounts_table(conn: psycopg.Connection) -> None:
    """The FK target has to exist before a column can point at it.

    Imported lazily: accounts.py imports this module, so a top-level
    import would be a cycle. Idempotent -- the schema is all
    CREATE TABLE IF NOT EXISTS -- which matters because init order varies
    (the app lifespan runs accounts.init() itself; a test that only calls
    preprod.init() does not).
    """
    from .accounts import SCHEMA as ACCOUNTS_SCHEMA
    conn.execute(ACCOUNTS_SCHEMA)


def _ensure_owner_fk(conn: psycopg.Connection, table: str) -> bool:
    """`<table>_account_id_fkey`, the constraint SQLite declared inline
    and Postgres gets as a separate step (see add_account_column). True
    if it was added now. Looked up by name on the table's own oid, so it
    resolves on search_path like everything else."""
    name = f"{table}_account_id_fkey"
    present = conn.execute(
        "SELECT 1 FROM pg_constraint WHERE conrelid = %s::regclass AND conname = %s",
        (table, name),
    ).fetchone()
    if present:
        return False
    conn.execute(
        f"ALTER TABLE {table} ADD CONSTRAINT {name} "
        f"FOREIGN KEY (account_id) REFERENCES accounts(id)"
    )
    return True


def add_account_column(conn: psycopg.Connection, table: str) -> bool:
    """Additive ALTER TABLE, the preprod.picked_at pattern. True if added.

    Nullable on purpose. The only honest default -- a literal account id
    -- differs per database, so NULL means "predates tenancy" and
    backfill_owner is what claims those rows. Ownership is enforced by
    the queries, not by the column.

    Two idempotent halves: the column, then the FOREIGN KEY to
    accounts(id) as its own constraint. Separate because a module's
    SCHEMA may already carry the column inline (db.SCHEMA's videos does)
    but cannot carry the REFERENCES -- accounts.SCHEMA is in the module
    that imports this one -- so the constraint is always applied here,
    after _ensure_accounts_table has made the target exist.
    """
    _ensure_accounts_table(conn)
    added = "account_id" not in columns(conn, table)
    if added:
        conn.execute(f"ALTER TABLE {table} ADD COLUMN account_id BIGINT")
    _ensure_owner_fk(conn, table)
    return added


def bootstrap_account_id(conn: psycopg.Connection) -> Optional[int]:
    """The account pre-tenancy rows belong to: the oldest one, which on
    every database that exists today is Mike's. None before seeding."""
    if not table_exists(conn, "accounts"):
        return None
    row = conn.execute("SELECT MIN(id) AS id FROM accounts").fetchone()
    return row["id"] if row and row["id"] is not None else None


def backfill_owner(conn: psycopg.Connection, table: str,
                   account_id: Optional[int] = None) -> int:
    """Claim every ownerless row for the bootstrap account; returns how
    many. A no-op when there is no account yet -- init() runs before
    seed() on a fresh database, so accounts.seed() calls this again once
    there is finally an owner to claim them for."""
    if account_id is None:
        account_id = bootstrap_account_id(conn)
    if account_id is None:
        return 0
    cur = conn.execute(
        f"UPDATE {table} SET account_id = %s WHERE account_id IS NULL",
        (account_id,),
    )
    return cur.rowcount


def own_table(conn: psycopg.Connection, table: str) -> None:
    """add_account_column + backfill_owner -- the pair every init() wants."""
    add_account_column(conn, table)
    backfill_owner(conn, table)


def init_db(dsn: Optional[str] = None) -> None:
    """Create the tables. Safe to run repeatedly.

    The SQLite-era migrations that used to live here (add videos.brand,
    add videos.concept_id) are gone: they upgraded a file that predated
    those columns, and no Postgres database predates anything -- both
    are in the CREATE TABLE. own_table stays: it is what declares the
    FK to accounts(id), which cannot be inline (see SCHEMA).
    """
    with connect(dsn) as conn:
        conn.execute(SCHEMA)
        # tenancy: a posted video belongs to the account that made it
        own_table(conn, "videos")


