# Age of a snapshot in days, the julianday() difference translated. Both
# columns are ISO text: `posted_at` is usually date-only, `captured_at`
# usually a full timestamp. The cast reads both, and connect() pins the
# session to UTC so a date-only value means midnight UTC the way SQLite's
# julianday() always did.
_AGE_DAYS = (
    "extract(epoch from (m.captured_at::timestamptz"
    " - v.posted_at::timestamptz)) / 86400"
)


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _hash(text: str | None) -> str | None:
    """Short content hash, so you can tell which prompt version produced what."""
    if text is None:
        return None
    return hashlib.sha256(text.encode()).hexdigest()[:12]


class Row(dict):
    """A result row: a dict by column name AND a sequence by position.

    That is the sqlite3.Row contract every caller was written against --
    `row["id"]`, `row[0]`, `dict(row)` -- and psycopg's stock factories
    give one or the other, never both.

    The positions are kept as their own tuple, not read back out of the
    dict: `SELECT COUNT(*), SUM(a), SUM(b)` names its columns `count`,
    `sum`, `sum`, and a dict keeps one `sum`. Reading `row[2]` off the
    dict's values was an IndexError (autonomy.prompt_gate_agreement).
    """

    __slots__ = ("_values",)

    def __init__(self, names, values):
        super().__init__(zip(names, values))
        self._values = tuple(values)

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)

    # Iterating and unpacking yield VALUES, as sqlite3.Row did:
    # `prompt, params = conn.execute(...).fetchone()` is a pattern the
    # tests use. dict(row), row.keys(), `k in row` and **row still see
    # the mapping -- CPython's dict() takes the generic keys() path once
    # __iter__ is overridden, and that path is correct here.
    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)


def _row_factory(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []

    def make(values):
        return Row(names, values)

    return make


def resolve_dsn(dsn: Optional[str] = None) -> str:
    """The connection URL: an explicit one, else DATABASE_URL, else the
    compose box."""
    return dsn or os.environ.get("DATABASE_URL") or DEFAULT_DSN


@contextmanager
def connect(dsn: Optional[str] = None) -> Iterator[psycopg.Connection]:
    """Commits on success, rolls back on error, always closes."""
    conn = psycopg.connect(resolve_dsn(dsn), row_factory=_row_factory)
    try:
        # See _AGE_DAYS: the date arithmetic is only right in UTC.
        conn.execute("SET TIME ZONE 'UTC'")
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


