"""
The spine: what got pitched, what got shot, how it did.

Four tables:

    pitch_runs - one execution of pitch.py against a manifest
    ideas      - one pitch. 10 per run. `selected` records your choice.
    videos     - something you actually posted
    metrics    - a snapshot of how a video was doing at one moment

Two design decisions worth knowing.

`selected` on ideas exists because pitch.py generates 10 and you pick a
few. That choice is a human label. Ten pitches from the same manifest
under the same prompt, three marked good, seven not — that is a
preference set, and it is the only source of ground truth in this
system that does not require waiting for a video to be posted.

`metrics` is its own table because numbers change. A video has 8k views
on day one and 40k on day thirty. Overwrite the row and you lose the
growth curve, and you can no longer compare a video posted yesterday
against one posted last year. Snapshots let you ask "how did each look
at 7 days old", which is the only fair comparison.

Postgres since 2026-09-03 (docs/tasks/task-postgres-migration.md, step 1
of the module order). It was SQLite for a year because that needed no
setup; it moved because row-level security is the structural fix for the
owner-predicate class of bug the pilot dry run found, and RLS wants a
real server. Postgres ONLY -- no dual code path. The connection URL is
`DATABASE_URL` (the name docs/DEPLOY_FLY.md already uses), and every
function takes `dsn` where it used to take `path`. `DB_PATH` still names
the legacy SQLite file: the data copy reads from it, and the modules not
yet ported still import it.

The dialect choices, each from the migration doc's translation table:
`%s` placeholders; `IS NOT DISTINCT FROM` where SQLite had `IS ?` (a
plain `=` silently drops every NULL-owned row -- a different bug from
the one tenancy fixed); `RETURNING id` instead of `lastrowid`;
identity columns are `GENERATED BY DEFAULT AS IDENTITY` (Mike's call,
2026-09-03: `ALWAYS` refuses the explicit ids the SQLite data copy has
to preserve); `julianday(a) - julianday(b)` is
`extract(epoch from (a::timestamptz - b::timestamptz)) / 86400`, which
is only equivalent with the session in UTC -- connect() sets that,
because a date-only `posted_at` cast in a local-time session would be
hours off from a full ISO `captured_at` carrying `+00:00`.
"""

