def _terms(q: str) -> list[str]:
    return [t for t in (w.strip(".,!?;:\"'()").lower() for w in (q or "").split()) if len(t) >= 3]


def search(q: str, *, account_id: Optional[int], k: int = 10, query_vector=None,
           dsn: Optional[str] = None) -> dict[str, Any]:
    """{"results": [...], "notes": [...]} for a plain-words query.

    `query_vector` is the query's RETRIEVAL_QUERY embedding (the caller
    embeds, so this module never needs a Gemini client -- the rag.py
    edge/generator split). None runs the text half alone."""
    q = (q or "").strip()
    if not q:
        return {"results": [], "notes": ["an empty search finds nothing"]}
    k = max(1, min(int(k), 50))
    notes: list[str] = []
    ranked: dict[int, dict] = {}
    with db.connect(dsn) as conn:
        if not db.table_exists(conn, "media_moments"):
            return {"results": [], "notes": ["nothing has been indexed yet"]}
        if query_vector is not None:
            vs = _vector_schema(conn)
            near = f"embedding OPERATOR({vs}.<=>) %s::{vs}.vector"
            rows = conn.execute(
                "SELECT id, media, kind, start_f, end_f, speaker, text, tags, "
                f"1 - ({near}) AS similarity FROM media_moments "
                "WHERE account_id IS NOT DISTINCT FROM %s AND embedding IS NOT NULL "
                f"ORDER BY {near} LIMIT %s",
                (_vec(query_vector), account_id, _vec(query_vector), k * 3)).fetchall()
            for rank, r in enumerate(rows):
                hit = ranked.setdefault(r["id"], {**dict(r), "score": 0.0, "matched": []})
                hit["score"] += 1.0 / (RRF_K + rank)
                hit["matched"].append("meaning")
        else:
            notes.append("searched the words only -- no embedding key, so meaning was not used")
        terms = _terms(q) or [q.lower()]
        like = [f"%{t}%" for t in terms]
        rows = conn.execute(
            "SELECT id, media, kind, start_f, end_f, speaker, text, tags FROM media_moments "
            "WHERE account_id IS NOT DISTINCT FROM %s AND ("
            + " OR ".join(["(lower(text) LIKE %s OR lower(COALESCE(tags::text, '')) LIKE %s)"]
                          * len(like))
            + ") LIMIT %s",
            (account_id, *[x for pat in like for x in (pat, pat)], k * 6)).fetchall()
        # more terms matched ranks higher; an exact word (a word row) is the
        # most specific answer a text match can give
        def weight(r):
            text = f"{r['text']} {json.dumps(r['tags'] or '')}".lower()
            return (sum(t in text for t in terms), r["kind"] == "word")
        for rank, r in enumerate(sorted(rows, key=weight, reverse=True)):
            hit = ranked.setdefault(r["id"], {**dict(r), "score": 0.0, "matched": []})
            hit["score"] += 1.0 / (RRF_K + rank)
            hit["matched"].append("words")
        fps_rows = conn.execute(
            "SELECT media, fps FROM media_index WHERE account_id IS NOT DISTINCT FROM %s",
            (account_id,)).fetchall()
    fps = {r["media"]: r["fps"] for r in fps_rows}
    hits = sorted(ranked.values(), key=lambda h: h["score"], reverse=True)[:k]
    for h in hits:
        f = fps.get(h["media"]) or d.DEFAULT_FPS
        h["start_s"] = round(h["start_f"] / f, 2)
        h["end_s"] = round(h["end_f"] / f, 2)
        h["score"] = round(h["score"], 5)
        h.pop("similarity", None)
    return {"results": hits, "notes": notes}
