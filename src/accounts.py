#!/usr/bin/env python3
"""
Users, accounts, membership -- the real login's spine, on Supabase Auth.

Identity is Supabase's (2026-09-03, step 6 of
docs/tasks/task-postgres-migration.md, Mike's call): `auth.users` in the
Supabase project owns who a person is, how they prove it (Google,
Discord, email+password) and their password. This module keeps what
Supabase cannot know -- which of OUR accounts a person may enter:

- `users`           a PROFILE MIRROR of auth.users, keyed by the same
                    UUID, holding email / display_name / avatar_url. No
                    password_hash, no identities: those left with the
                    hand-rolled OAuth. No FOREIGN KEY into auth.users
                    either -- the `auth` schema is Supabase's, and the
                    throwaway Postgres the tests run on has no such
                    schema; the writer (`claim`) enforces the link.
- `accounts`        a brand (zeropage / antihero -- what the hardcoded
                    BRANDS tuple grows up into), and the tenant.
- `account_members` who may enter which account.

The gate that matters lives in the shape of this data: a fresh sign-in
gets a users row and ZERO account_members rows. Membership is granted
by an existing member (`invite`) -- or, since 2026-09-24 and while
`open_signup()` is on (the default), by `provision_personal`, which
gives a brand-new sign-in its OWN empty workspace. It never adds anyone
to an existing account. `ZEROPAGE_OPEN_SIGNUP=0` restores invite-only.

**The invite still works before the person has ever visited.** An
invite creates a users row by EMAIL with a locally minted placeholder
id and `claimed_at` NULL. The first Supabase sign-in with that email
(`claim`) rewrites the row's id to the real auth.users UUID -- the FK on
account_members says ON UPDATE CASCADE, so the membership follows --
and stamps claimed_at. So there is no secret to send anyone.

Extends db.py in its own module (own SCHEMA, own init()), the
preprod.py pattern. Every function takes `dsn` (None = DATABASE_URL).
"""
from __future__ import annotations

import argparse
import sys
import uuid
from datetime import datetime, timezone
from typing import Any, Optional

from .db import (
    OWNED_TABLES,
    add_billing_columns,
    add_manual_lane_operator_column,
    add_prompt_edits_teach_column,
    backfill_owner,
    columns,
    connect,
    table_exists,
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    -- auth.users.id once claimed; a placeholder uuid4 for an invited
    -- person who has not signed in yet (claimed_at IS NULL)
    id            TEXT PRIMARY KEY,
    created_at    TEXT NOT NULL,
    email         TEXT NOT NULL UNIQUE,
    display_name  TEXT,
    avatar_url    TEXT,
    claimed_at    TEXT
);

CREATE TABLE IF NOT EXISTS accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TEXT NOT NULL,
    slug           TEXT NOT NULL UNIQUE,
    display_name   TEXT NOT NULL,
    accent_color   TEXT,
    voice          TEXT,
    house_look     TEXT,
    house_negative TEXT,
    house_aspect   TEXT DEFAULT '9:16',
    never_list     TEXT,
    -- may this account spend the OPERATOR'S personal consumer plans
    -- (src/manual_lane.py)? FALSE for every account that has ever been
    -- created, including the bootstrap one: the lane fails closed and
    -- the only way in is somebody turning it on by hand. db.py carries
    -- the ALTER for databases that predate the column.
    manual_lane_operator BOOLEAN NOT NULL DEFAULT FALSE,
    -- billing (docs/tasks/task-stripe-billing.md, 2026-09-18): does this
    -- account render without being charged (the operator's own, by
    -- hand, same fail-closed shape as the lane); which Stripe customer
    -- pays for it; which plan its subscription bought (pricing.PLANS
    -- keys; NULL is no subscription, never a default).
    credit_exempt      BOOLEAN NOT NULL DEFAULT FALSE,
    stripe_customer_id TEXT,
    plan               TEXT,
    -- may a hand edit of this account's scene prompts teach the RAG
    -- shelves (src/edit_teach.py)? Same posture: FALSE until turned on.
    prompt_edits_teach BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS account_members (
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    user_id    TEXT   NOT NULL REFERENCES users(id) ON UPDATE CASCADE,
    role       TEXT   NOT NULL DEFAULT 'owner',
    PRIMARY KEY (account_id, user_id)
);
"""


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")


def init(dsn: Optional[str] = None) -> None:
    """Create the auth tables. Run after db.init_db()."""
    with connect(dsn) as conn:
        conn.execute(SCHEMA)
        # a live database predates manual_lane_operator (2026-09-08); the
        # CREATE TABLE above carries it for a fresh one, and db.init_db
        # runs before this table exists at all, so the ALTER is asked for
        # here as well as there -- both are no-ops once it has landed.
        add_manual_lane_operator_column(conn)
        add_billing_columns(conn)
        add_prompt_edits_teach_column(conn)


