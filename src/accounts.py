def upsert_account(slug: str, display_name: str, accent_color: Optional[str] = None,
                   dsn: Optional[str] = None) -> int:
    with connect(dsn) as conn:
        row = conn.execute("SELECT id FROM accounts WHERE slug = %s", (slug,)).fetchone()
        if row:
            return int(row["id"])
        row = conn.execute(
            "INSERT INTO accounts (created_at, slug, display_name, accent_color) "
            "VALUES (%s, %s, %s, %s) RETURNING id",
            (_now(), slug, display_name, accent_color),
        ).fetchone()
        return int(row["id"])


def add_member(account_id: int, user_id: str, role: str = "owner",
               dsn: Optional[str] = None) -> None:
    with connect(dsn) as conn:
        conn.execute(
            "INSERT INTO account_members (account_id, user_id, role) "
            "VALUES (%s, %s, %s) ON CONFLICT (account_id, user_id) DO NOTHING",
            (account_id, str(user_id), role),
        )


def memberships(user_id: str, dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """The accounts this user may enter. Empty list == signed in but no
    access -- the state the membership gate renders, fixed only by an
    invite or, at sign-in, by provision_personal (open sign-up)."""
    with connect(dsn) as conn:
        rows = conn.execute(
            "SELECT a.*, m.role FROM accounts a "
            "JOIN account_members m ON m.account_id = a.id "
            "WHERE m.user_id = %s ORDER BY a.slug",
            (str(user_id),),
        ).fetchall()
        return [dict(r) for r in rows]


