def grant(account_id: Optional[int], credits: int, kind: str, *,
          source_ref: Optional[str] = None, note: Optional[str] = None,
          granted_at: Optional[str] = None, expires_at: Optional[str] = None,
          dsn: Optional[str] = None) -> int:
    """Add a lot of credit. Returns the lot id. RAISES on anything wrong.

    `source_ref` is the Stripe payment intent or the subscription period
    id, and it is the webhook guard: a second delivery of the same event
    hits the unique index on (account_id, kind, source_ref) and returns
    THE EXISTING LOT rather than granting twice. That check is done by
    reading first -- inside the account's advisory lock, so two
    deliveries racing each other cannot both find nothing.

    `expires_at` defaults to EXPIRY_MONTHS after the grant. Pass it
    explicitly only where a plan really does say something else; the
    default is the policy.
    """
    credits = int(credits)
    if credits <= 0:
        raise LedgerError(f"a grant must be positive, got {credits}")
    if kind not in LOT_KINDS:
        raise LedgerError(f"lot kind must be one of {LOT_KINDS}, got {kind!r}")
    granted_at = granted_at or _now()
    if expires_at is None:
        expires_at = _plus_months(granted_at, EXPIRY_MONTHS)

    with db.connect(dsn) as conn:
        _lock(conn, account_id)
        if source_ref is not None:
            existing = conn.execute(
                "SELECT id FROM credit_lots WHERE account_id IS NOT DISTINCT FROM %s "
                "AND kind = %s AND source_ref = %s",
                (account_id, kind, source_ref),
            ).fetchone()
            if existing:
                return int(existing["id"])
        lot_id = conn.execute(
            "INSERT INTO credit_lots (account_id, kind, credits_granted, "
            "credits_remaining, granted_at, expires_at, source_ref, note) "
            "VALUES (%s, %s, %s, 0, %s, %s, %s, %s) RETURNING id",
            (account_id, kind, credits, granted_at, expires_at, source_ref, note),
        ).fetchone()["id"]
        # credits_remaining starts at 0 and the grant ENTRY is what puts
        # the credit in it, so the invariant reconcile() checks holds
        # from the lot's first instant rather than from its second.
        _entry(conn, account_id=account_id, lot_id=int(lot_id), delta=credits,
               kind="grant", ref=source_ref or f"grant:lot:{lot_id}")
        return int(lot_id)


