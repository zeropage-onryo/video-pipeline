def hold_for_render(account_id: Optional[int], *, ref: str, provider: str,
                    estimate_usd, key_source: Optional[str] = None,
                    dsn: Optional[str] = None) -> Optional[int]:
    """Take the hold for one render, or None when the render is not
    billable. THE SEAM -- NOTHING CALLS IT YET, ON PURPOSE.

    WHERE THIS CALL GOES, when the wiring pass happens (this pass builds
    the module and its tests only; the adapters keep working exactly as
    they do today):

    - `src/runway.py::generate_video`, immediately before
      `client.image_to_video.create(...)` -- the single irreversible
      submit, currently around line 243, after the spend gate and after
      the client is built.
    - `src/higgsfield.py::_submit_and_wait`, immediately before
      `http(HOST + path, body)` -- the submit that every higgsfield
      render (video, soul, the lot) funnels through.
    - `src/veo.py::generate_video`, immediately before
      `client.models.generate_videos(...)`.

    BEFORE the submit, never after: everything before that HTTP call is
    intention and everything after it is bookkeeping the provider does
    not care about. Today the `generations` row -- the only record that
    a render happened -- is written after the call returns, across a
    poll loop that can run for minutes, so a crash in that window means
    the provider billed and nothing here knows. If this raises,
    InsufficientCredit or otherwise, no HTTP call is made and no money
    moves.

    The caller owes three things, and the reaper covers only the third:

        ledger.mark_submitted(hold_id)                   # LAST line before the submit
        ...the provider call...
        settle(hold_id, actual_usd, generation_id=...)   # delivered, passed QC
        release(hold_id, "provider error: ...")          # failed, timed out, QC'd out

    and must pass `ledger.ref_params(ref)` into the render's
    `generations` params, or the reaper cannot match the hold to the row.

    `mark_submitted` is not optional bookkeeping. It is what lets the
    reaper tell a render that never happened (release it, quietly) from
    one the provider billed for and nothing recorded (leave it
    outstanding, shout about it). Skip it and every dead worker looks
    like a free refund.

    `key_source` is what `account_keys.key_source(account_id, provider)`
    returned for this render -- the same value the adapter already
    writes into `generations.params_json`. On "account" this returns
    None and takes NO hold: see `is_billable`.
    """
    if not is_billable(key_source):
        return None
    return hold(account_id, credits_for_usd(estimate_usd), ref=ref,
                provider=provider, estimate_usd=estimate_usd, dsn=dsn)


