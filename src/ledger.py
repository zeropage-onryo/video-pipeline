"""
The prepaid credit ledger: what an account has, what it has committed,
and what it actually consumed.

WHY THIS EXISTS, AND WHY IT DOES NOT LOOK LIKE ITS NEIGHBOURS
(docs/CREDIT_LEDGER_DESIGN.md, written 2026-09-08 before a line of this).
`src/spend.py` and `src/costs.py` already meter, and they are
deliberately never-raises: a lost `llm_calls` row costs a number on a
dashboard and nothing else. This module is the opposite promise. A
ledger write that silently fails costs MONEY -- either the customer's,
by charging twice, or yours, by rendering for free -- so **every write
here raises**. Do not copy `record_call`'s swallow-everything shape into
this file; it is the single most important difference between the two
modules that otherwise look alike.

THE UNIT IS AN INTEGER. One credit is one US cent. `BIGINT`, no
`NUMERIC`, no floats anywhere on the ledger path. The `cost_usd` columns
on `generations` and `llm_calls` stay floats -- they are estimates for a
page and are not this. Dollars become credits at exactly one place,
`credits_for_usd()`, which rounds UP, so rounding never quietly favours
the customer at your expense across thousands of renders.

CREDIT ARRIVES IN LOTS, NOT AS A BALANCE. An allowance granted by a plan
and a credit bought with cash are different promises even when they
expire on the same clock, so each grant is its own row carrying its own
expiry and its own lapse policy, and consumption is SOONEST-EXPIRY-FIRST
across them. That is what makes "your monthly allowance burns before the
credit you paid for" true without anyone having to remember it, and it
is what lets the two kinds be governed differently later without a
migration.

THE HOLD IS THE POINT OF THE WHOLE EXERCISE. The irreversible commit is
the single HTTP submit inside each adapter (see `hold_for_render` for
the exact sites), and today the `generations` row is written *after* it,
across a poll loop that can run for minutes. So the ledger writes
BEFORE the submit: hold -> submit -> settle or release. And the hold
takes a per-account advisory lock, because `generative.cap_error` is
already read-then-act with no lock -- which is why two simultaneous
approvals can both pass a cap of six -- and money must not inherit that.

Postgres, like every table since 2026-09-03: `%s` placeholders,
`IS NOT DISTINCT FROM` for the nullable owner (a plain `=` silently
drops every unowned row), `RETURNING id`, `GENERATED BY DEFAULT AS
IDENTITY`, and `dsn` where a `path` used to be.

Both tables are OWNED (`db.OWNED_TABLES`). Every literal that names one
carries `account_id` in the SAME string, because the scanner in
tests/test_tenancy.py cannot see a predicate assembled next door.

THREE THINGS THAT LOOK WRONG AND ARE KNOWN, so the next reader spends
their afternoon on something else:

- `credit_lots.credits_remaining` IS A DENORMALISATION. The entries are
  the truth; that column is the running figure the lot-picking queries
  read, and `reconcile()` plus a test assert the two never disagree.
  Nothing at the database level enforces it, which is the real gap --
  a trigger, or dropping the column and reading `SUM(delta)` off an
  index, would make the invariant unfalsifiable rather than merely
  tested. Left as it is on purpose: the check has teeth today and the
  fix is cheap the day it does not.

- THE RECONCILIATION FIGURE THE DESIGN DOC DESCRIBES IS CIRCULAR while
  settle runs on the same estimate `generations.cost_usd` records --
  "settled vs metered drift" compares a number against itself and will
  read ~0 forever. It is a consistency check, not a financial one, and
  should not be shown as reassurance until a real per-render invoice
  exists (fal publishes per-second rates; Runway and Higgsfield do
  not). `reconcile()` here is the honest one: entries against the
  running figure, both of them this module's own.

- `LAPSE_POLICY["purchase"] = True` VOIDS CREDIT SOMEBODY PAID CASH
  FOR. That is flagged in the design doc as the entry to revisit, and
  it is the owner's call, not this module's. It is a constant here
  precisely so softening it is one line and no migration.
"""
from __future__ import annotations

