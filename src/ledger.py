# hold -- the atomic one
# --------------------------------------------------------------------------

def _hold_group(conn, hold_id: int) -> tuple[Optional[int], str, list[dict]]:
    """(account_id, ref, the hold's entries in the order they were
    taken) for a hold id. Raises if it is not a hold."""
    head = conn.execute(
        "SELECT id, account_id, ref FROM credit_entries WHERE id = %s AND kind = 'hold'",
        (hold_id,),
    ).fetchone()
    if not head:
        raise LedgerError(f"no hold with id {hold_id}")
    account_id, ref = head["account_id"], head["ref"]
    rows = conn.execute(
        "SELECT * FROM credit_entries WHERE account_id IS NOT DISTINCT FROM %s "
        "AND ref = %s AND kind = 'hold' ORDER BY id ASC",
        (account_id, ref),
    ).fetchall()
    return account_id, ref, [dict(r) for r in rows]


def _resolved(conn, account_id: Optional[int], ref: str) -> Optional[str]:
    """'settle' or 'release' if this hold is already finished, else None."""
    row = conn.execute(
        "SELECT kind FROM credit_entries WHERE account_id IS NOT DISTINCT FROM %s "
        "AND ref = %s AND kind IN ('settle', 'release') LIMIT 1",
        (account_id, ref),
    ).fetchone()
    return row["kind"] if row else None


def hold(account_id: Optional[int], credits: int, *, ref: str, provider: str,
         estimate_usd: Optional[float] = None, dsn: Optional[str] = None) -> int:
    """Commit `credits` against this account, or raise InsufficientCredit.
    Returns a hold id to settle or release. Nothing has been spent yet.

    ONE TRANSACTION, AND THE ORDER INSIDE IT IS THE WHOLE POINT:

        1. pg_advisory_xact_lock on this account
        2. is this `ref` already held?  -> return the existing hold
        3. compute the available balance
        4. insert the negative entries, soonest-expiry lot first
        5. commit, which releases the lock

    Read-then-act is only safe between 1 and 5. `generative.cap_error`
    is the same shape WITHOUT the lock, which is why two simultaneous
    approvals can both pass a cap of six -- an annoyance there, and
    money here. Two concurrent holds on a balance that fits one: exactly
    one commits, the other sees the first's entries and raises.

    `ref` IS THE IDEMPOTENCY KEY. A caller that retries across a network
    blip gets the same hold id back rather than a second debit, and the
    unique index on (account_id, kind, ref, lot_id) is the backstop if
    some future writer skips the lock.

    `provider` and the estimate are the reaper's evidence -- without
    them it cannot tell a dead render from a slow one. The estimate is
    stored as the hold's own `delta`, in credits, rather than as a
    dollars column: no float goes on this path. `estimate_usd` is
    accepted for the caller's convenience (`hold_for_render` converts
    with it) and reconciled against `credits` rather than stored.
    """
    credits = int(credits)
    if credits <= 0:
        raise LedgerError(f"a hold must be positive, got {credits}")
    if not ref:
        raise LedgerError("a hold needs a ref -- it is the idempotency key")
    if estimate_usd is not None and credits_for_usd(estimate_usd) != credits:
        raise LedgerError(
            f"hold of {credits} credits does not match estimate_usd {estimate_usd} "
            f"({credits_for_usd(estimate_usd)} credits) -- convert once, at "
            f"credits_for_usd, and pass the same number to both")

    now = _now()
    with db.connect(dsn) as conn:
        _lock(conn, account_id)

        prior = conn.execute(
            "SELECT MIN(id) AS id FROM credit_entries "
            "WHERE account_id IS NOT DISTINCT FROM %s AND ref = %s AND kind = 'hold'",
            (account_id, ref),
        ).fetchone()
        if prior and prior["id"] is not None:
            return int(prior["id"])

        have = _available(conn, account_id, now)
        if have < credits:
            raise InsufficientCredit(account_id, credits, have)

        rows = conn.execute(
            "SELECT id, credits_remaining FROM credit_lots "
            "WHERE account_id IS NOT DISTINCT FROM %s AND credits_remaining > 0 "
            "AND (expires_at IS NULL OR expires_at > %s) "
            "ORDER BY expires_at ASC NULLS LAST, id ASC",
            (account_id, now),
        ).fetchall()

        wanted, first_id = credits, None
        for row in rows:
            if wanted <= 0:
                break
            take = min(wanted, int(row["credits_remaining"]))
            entry_id = _entry(conn, account_id=account_id, lot_id=int(row["id"]),
                              delta=-take, kind="hold", ref=ref, provider=provider)
            first_id = first_id or entry_id
            wanted -= take
        if wanted > 0:
            # The balance said yes and the lots could not pay it. That is
            # a corrupted ledger, not a poor customer -- raising rolls
            # the whole transaction back, which is why the lot rows are
            # only ever touched inside one.
            raise LedgerError(
                f"account {account_id}: available balance {have} but only "
                f"{credits - wanted} credits found in unexpired lots -- run "
                f"ledger.reconcile()")
        return int(first_id)


def mark_submitted(hold_id: int, dsn: Optional[str] = None) -> str:
    """Stamp a hold the instant before the provider call. Returns the
    stamp. Idempotent: a second call returns the first one's timestamp.

    WHY THIS EXISTS. Without it, "the render never happened" and "the
    render was submitted, the provider billed, and the worker died
    before anything recorded it" are the same observation -- an
    outstanding hold with no `generations` row -- and they have opposite
    correct answers. Releasing the first is right; releasing the second
    gives away a render you paid for and, worse, erases the only
    evidence that it happened.

    It goes between `hold_for_render` and the submit, in the same few
    lines:

        hold_id = ledger.hold_for_render(...)
        ledger.mark_submitted(hold_id)        # <- here
        task = client.image_to_video.create(...)

    The window between the stamp and the HTTP call is the one this
    cannot close, and it is deliberately the safe side to be wrong on:
    a stamp with no submit reads as an orphan a human looks at and
    releases by hand, while a submit with no stamp is money silently
    given back.
    """
    stamp = _now()
    with db.connect(dsn) as conn:
        row = conn.execute(
            "SELECT account_id, ref, submitted_at FROM credit_entries "
            "WHERE id = %s AND kind = 'hold'", (hold_id,)).fetchone()
        if not row:
            raise LedgerError(f"no hold with id {hold_id}")
        if row["submitted_at"]:
            return str(row["submitted_at"])
        # Every entry of the hold, because a hold may span several lots
        # and the fact being recorded is about the RENDER, not the lot.
        # NULL-guarded so a re-stamp can never move a submit time
        # backwards or forwards -- the column goes NULL -> value, once.
        conn.execute(
            "UPDATE credit_entries SET submitted_at = %s "
            "WHERE account_id IS NOT DISTINCT FROM %s AND ref = %s "
            "AND kind = 'hold' AND submitted_at IS NULL",
            (stamp, row["account_id"], row["ref"]),
        )
        return stamp


