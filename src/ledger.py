# Where credit came from. `adjustment` is the operator's correction --
# a goodwill top-up, a botched night made good -- and is deliberately
# NOT in LAPSE_POLICY's True set below.
LOT_KINDS = ("subscription", "purchase", "refund", "promo", "adjustment")

# Every movement. Nothing is ever updated or deleted; a correction is
# another row.
ENTRY_KINDS = ("grant", "hold", "settle", "release", "expire")

# Changed 2026-09-08 (design doc, "Expiry and lapse"): two months from
# grant, not the twelve the first draft carried.
EXPIRY_MONTHS = 2

# Which lot kinds die when the subscription lapses. A dict rather than a
# hardcoded rule because THE `purchase` ENTRY IS THE ONE TO REVISIT:
# voiding credit a customer paid cash for, because a separate
# subscription ended, is the shape that draws chargebacks -- and prepaid
# balances fall under gift-card and escheatment law in many states, with
# minimum honor periods measured in years rather than months. Softening
# it should be an edit to this line after an accountant has looked at
# it, not a migration. `refund` is False because refunded credit is
# money you already owed back; `adjustment` is absent (and therefore
# False) for the same reason -- an operator's correction should not be
# undone by a billing event.
LAPSE_POLICY: dict[str, bool] = {
    "subscription": True,
    "purchase": True,
    "promo": True,
    "refund": False,
}

# The key an adapter puts in its `generations.params_json` so the reaper
# can find the row a hold was taken for. See `ref_params` and `reap`.
GENERATION_REF_KEY = "ledger_ref"

# How old an unsettled hold has to be before the nightly reaper touches
# it. Well past the longest provider poll loop in the repo (Veo's
# timeout_s is 600s) -- reaping a hold whose render is merely slow would
# settle or release a render that is still running.
DEFAULT_REAP_AGE = timedelta(hours=6)


class LedgerError(RuntimeError):
    """Anything the ledger refuses to do. Raised, never swallowed."""


class InsufficientCredit(LedgerError):
    """`hold()` could not fit the request inside the available balance.

    Carries the numbers so a caller can say what it needs rather than
    "payment required": both are integer credits, both are the truth at
    the moment the advisory lock was held.
    """

    def __init__(self, account_id: Optional[int], requested: int, available: int):
        self.account_id = account_id
        self.requested = int(requested)
        self.available = int(available)
        super().__init__(
            f"account {account_id} has {self.available} credits available, "
            f"needs {self.requested}"
        )


