# expiry and lapse
# --------------------------------------------------------------------------

def _expire_lot(conn, account_id: Optional[int], lot: dict) -> int:
    """Write the `expire` entry for one lot. Returns credits expired.

    NEVER ZEROES THE LOT IN PLACE. The design doc's open question --
    whether credit expired by lapse is restored when somebody
    resubscribes -- is answerable either way only while the movement is
    a row: an `expire` entry of -400 can be reversed by a +400 grant
    that cites it, whereas an UPDATE that set credits_remaining = 0
    has destroyed the number it would have to restore.

    A lot with nothing left, or one already overdrawn, gets no entry:
    there is nothing to take, and taking a NEGATIVE remainder would
    write a POSITIVE delta -- expiry handing a customer who overdrew a
    gift.
    """
    remaining = int(lot["credits_remaining"])
    if remaining <= 0:
        return 0
    _entry(conn, account_id=account_id, lot_id=int(lot["id"]), delta=-remaining,
           kind="expire", ref=f"expire:lot:{lot['id']}")
    return remaining


def expire_due(account_id: Optional[int] = None, *, now: Optional[str] = None,
               dsn: Optional[str] = None) -> int:
    """Sweep every lot past its expiry date. Returns credits expired.

    `account_id=None` sweeps the whole installation, which is what the
    nightly walk wants; pass one to sweep a single account. The
    predicate is in the SQL either way -- `%s IS NULL OR account_id IS
    NOT DISTINCT FROM %s` -- so this is a scoped query the operator is
    allowed to widen, not an unscoped one with an excuse.

    Expiry is ALSO enforced on read (`_available`), so this sweep is
    about the audit trail, not about correctness of the balance: it is
    what makes the ledger say where the credit went instead of leaving
    a lot that silently stopped counting.
    """
    now = now or _now()
    expired = 0
    with db.connect(dsn) as conn:
        if account_id is not None:
            _lock(conn, account_id)
        rows = conn.execute(
            "SELECT id, account_id, credits_remaining FROM credit_lots "
            "WHERE (%s::bigint IS NULL OR account_id IS NOT DISTINCT FROM %s) "
            "AND expires_at IS NOT NULL AND expires_at <= %s AND credits_remaining > 0 "
            "ORDER BY id ASC",
            (account_id, account_id, now),
        ).fetchall()
        for row in rows:
            # One lock per account touched, taken inside the same
            # transaction so they all release together on commit. The
            # installation-wide sweep must not serialise on one global
            # key: two customers expiring have nothing to do with each
            # other, and a lock they share is a lock that will one day
            # be held while somebody's hold waits behind it.
            if account_id is None:
                _lock(conn, row["account_id"])
            expired += _expire_lot(conn, row["account_id"], dict(row))
    return expired


def on_subscription_lapsed(account_id: Optional[int], dsn: Optional[str] = None) -> int:
    """The subscription ended: expire every lot whose kind says it dies.
    Returns credits expired.

    Called by whatever owns subscription state -- Stripe's webhook,
    later. The policy is LAPSE_POLICY and it is read here rather than
    written into the SQL, so softening `purchase` (which the design doc
    flags as the entry that draws chargebacks) is a one-line change with
    no migration behind it.

    A lot whose kind is not in LAPSE_POLICY survives, deliberately:
    `adjustment` -- the operator's own correction -- should not be undone
    by a billing event, and a kind added later defaults to surviving,
    which is the safe direction for something nobody has decided about.
    """
    dying = tuple(k for k, dies in LAPSE_POLICY.items() if dies)
    if not dying:
        return 0
    expired = 0
    with db.connect(dsn) as conn:
        _lock(conn, account_id)
        rows = conn.execute(
            "SELECT id, credits_remaining FROM credit_lots "
            "WHERE account_id IS NOT DISTINCT FROM %s AND kind = ANY(%s) "
            "AND credits_remaining > 0 ORDER BY id ASC",
            (account_id, list(dying)),
        ).fetchall()
        for row in rows:
            expired += _expire_lot(conn, account_id, dict(row))
    return expired


# --------------------------------------------------------------------------
# the reaper -- the thing that will actually go wrong
# --------------------------------------------------------------------------

def _log(message: str) -> None:
    print(f"[ledger] {message}", file=sys.stderr)


def _outstanding_holds(conn, account_id: Optional[int], cutoff: str) -> list[dict]:
    rows = conn.execute(
        """
        SELECT MIN(h.id) AS hold_id, h.account_id, h.ref, h.provider,
               -SUM(h.delta) AS held, MIN(h.created_at) AS created_at,
               MIN(h.submitted_at) AS submitted_at
        FROM credit_entries h
        WHERE (%s::bigint IS NULL OR h.account_id IS NOT DISTINCT FROM %s)
          AND h.kind = 'hold' AND h.created_at < %s
          AND NOT EXISTS (
                SELECT 1 FROM credit_entries d
                WHERE d.account_id IS NOT DISTINCT FROM h.account_id
                  AND d.ref = h.ref AND d.kind IN ('settle', 'release'))
        GROUP BY h.account_id, h.ref, h.provider
        ORDER BY MIN(h.id)
        """,
        (account_id, account_id, cutoff),
    ).fetchall()
    return [dict(r) for r in rows]


def _generation_for(conn, account_id: Optional[int], ref: str) -> Optional[dict]:
    """The `generations` row the render would have written, found by the
    `ledger_ref` an adapter puts in its params (see `ref_params`).

    Matched as a string rather than by casting params_json to jsonb:
    the column is TEXT written by json.dumps at several call sites, and
    one malformed row would make the cast raise for every hold in the
    sweep. A LIKE that finds nothing is the same answer as a row that
    is not there, which is exactly how the reaper should read it.
    """
    if not db.table_exists(conn, "generations"):
        return None
    row = conn.execute(
        "SELECT id, cost_usd, output_path, reject_reason FROM generations "
        "WHERE account_id IS NOT DISTINCT FROM %s AND params_json LIKE %s "
        "ORDER BY id DESC LIMIT 1",
        (account_id, f'%"{GENERATION_REF_KEY}": "{ref}"%'),
    ).fetchone()
    return dict(row) if row else None


def reap(older_than=DEFAULT_REAP_AGE, *, account_id: Optional[int] = None,
         dsn: Optional[str] = None) -> dict[str, Any]:
    """Close holds that outlived their renders. Runs on the nightly's
    schedule. Returns {"settled": [...], "released": [...], "orphaned": [...]}.

    A worker dies between submit and settle and the hold is a
    customer's balance held hostage forever. So for each outstanding
    hold past its age, look for the `generations` row the render would
    have written -- and, when it is not there, at whether the hold was
    ever stamped by `mark_submitted`:

    - found and usable (an output path, no reject reason) -> SETTLE at
      its `cost_usd`, falling back to the estimate the hold carries when
      the row was never priced.
    - found and failed -> RELEASE. The customer pays nothing; the cost
      lands in `waste_usd`.
    - absent, and NEVER SUBMITTED -> RELEASE, quietly. The render did
      not happen: the process died between the hold and the provider
      call, or the caller raised before it. Nothing was billed, so
      giving the credit back is simply correct and needs no attention.
    - absent, but SUBMITTED -> **ORPHANED.** Money was spent and
      nothing recorded it. The hold is LEFT OUTSTANDING, deliberately,
      and logged loudly.

    WHY AN ORPHAN IS NOT RELEASED. Releasing it would return the
    customer's credit for a render the provider really did bill you
    for, and -- the worse half -- it would erase the only trace that
    the discrepancy ever existed: an outstanding hold is visible in
    `outstanding()` and in every sweep from here on, while a released
    one is a closed pair of rows that looks exactly like a refunded
    failure. So an orphan stays open until a person decides, and it is
    reported on every subsequent run, on purpose, because a real-money
    discrepancy that stops being mentioned is one nobody fixes. The
    two ways to close one by hand, once somebody has looked at the
    provider's dashboard:

        settle(hold_id, actual_usd, generation_id=...)   # it did render
        release(hold_id, "orphan: provider has no record")

    `older_than` takes a timedelta (an age, the usual call) or a
    datetime (a cutoff, for a test that does not want to sleep).
    """
    if isinstance(older_than, timedelta):
        cutoff = (datetime.now(timezone.utc) - older_than).isoformat()
    elif isinstance(older_than, datetime):
        cutoff = older_than.isoformat()
    else:
        cutoff = str(older_than)

    settled: list[int] = []
    released: list[int] = []
    orphaned: list[int] = []
    with db.connect(dsn) as conn:
        pending = _outstanding_holds(conn, account_id, cutoff)
        found = {h["hold_id"]: _generation_for(conn, h["account_id"], h["ref"])
                 for h in pending}

    for h in pending:
        hold_id = int(h["hold_id"])
        gen = found.get(hold_id)
        usable = bool(gen and gen.get("output_path") and not gen.get("reject_reason"))
        if usable:
            actual = gen.get("cost_usd")
            actual_usd = float(actual) if actual is not None else int(h["held"]) / 100
            settle(hold_id, actual_usd, generation_id=int(gen["id"]), dsn=dsn)
            settled.append(hold_id)
            continue
        if gen is None:
            if h.get("submitted_at"):
                _log(f"ORPHAN HOLD {hold_id} ({h['provider']}, ref={h['ref']}, "
                     f"{h['held']} credits, submitted {h['submitted_at']}): the "
                     f"provider was submitted and NO generations row exists. That "
                     f"render was paid for and nothing recorded it. The hold is "
                     f"left outstanding on purpose -- releasing it would hand back "
                     f"credit for a render you were billed for and erase the only "
                     f"evidence of the loss. Check the provider's dashboard, then "
                     f"settle() or release() it by hand.")
                orphaned.append(hold_id)
                continue
            reason = "reaped: never submitted"
        else:
            reason = f"reaped: render failed ({gen.get('reject_reason') or 'no output'})"
        release(hold_id, reason, dsn=dsn)
        released.append(hold_id)
    return {"settled": settled, "released": released, "orphaned": orphaned}


