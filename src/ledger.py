def credits_for_usd(usd) -> int:
    """USD -> integer credits, ALWAYS ROUNDING UP. One credit = one cent.

    The only place in the codebase where a float becomes a credit, and
    it rounds up on purpose: a provider estimate of $0.4501 is 46
    credits, not 45. Rounded down, the half-cent you eat on each of ten
    thousand renders is $50 you cannot see in any row.

    Via Decimal(str(usd)) rather than `usd * 100`, because
    `0.29 * 100 == 28.999999999999996` and `math.ceil` of that is 29 by
    luck rather than by rule -- while `2.675 * 100` is 267.49999999999997
    and ceils to 268 correctly only because the error happened to fall
    the right way. str() takes the shortest repr, which is the number the
    caller meant.
    """
    if usd is None:
        raise LedgerError("cannot price None")
    try:
        cents = Decimal(str(usd)) * 100
    except (InvalidOperation, ValueError) as e:
        raise LedgerError(f"not a price: {usd!r}") from e
    if cents < 0:
        raise LedgerError(f"negative price: {usd!r}")
    return int(math.ceil(cents))


def ref_params(ref: str) -> dict:
    """The fragment an adapter merges into its `generations` params so a
    hold can be matched back to the render it paid for.

    `record_generation(..., params={**ledger.ref_params(ref), ...})` is
    the whole contract. The reaper matches on it as a string; the value
    is written by `json.dumps` on the way in, so it is exactly
    `"ledger_ref": "<ref>"` in the stored text.
    """
    return {GENERATION_REF_KEY: str(ref)}


# --------------------------------------------------------------------------
# BYOK -- one place, because every caller would get it wrong differently
# --------------------------------------------------------------------------

# What `account_keys.key_and_source` returns when the account rendered on
# its own stored credential rather than on the installation's env key.
BYOK_KEY_SOURCE = account_keys.SOURCE_ACCOUNT


def is_billable(key_source: Optional[str]) -> bool:
    """Whether a render on this credential may be debited. THE ONE PLACE
    that rule lives.

    A render whose credential resolved to `key_source == "account"` --
    the BYOK case `src/account_keys.py` made visible on 2026-09-07 --
    takes no hold and no debit: the customer's card was charged by the
    provider directly, and billing them again is charging twice for one
    clip. Every adapter already writes `key_source` into
    `generations.params_json`, so the fact is on the row; what must not
    happen is four call sites each deciding what to do with it, because
    the one that spells the constant wrong bills a BYOK customer and
    nothing fails.

    An UNKNOWN source (None -- no credential resolved at all, or
    `key_source()` swallowed a decrypt error) reads as billable. That is
    the deliberate direction to be wrong in: it holds credit for a
    render that may not happen, which `release()` and the reaper give
    back, rather than rendering for free on the installation's key and
    finding out at the invoice.
    """
    return key_source != BYOK_KEY_SOURCE


