def _available(conn, account_id: Optional[int], now: Optional[str] = None) -> int:
    """The available balance, from the entries -- the truth, not the
    denormalised `credits_remaining`.

    Two rules in one query. Per lot, `SUM(delta)` is what that lot has
    left: a grant, minus its holds, plus its releases, adjusted by its
    settles. Then a lot PAST ITS EXPIRY DATE contributes nothing --
    enforced on read, so a balance is right in the window between the
    date passing and `expire_due()` sweeping.

    The `LEAST(..., 0)` is the part worth reading twice. An expired lot
    is clamped to zero from ABOVE only: its unspent credit is gone, but
    an overdraft sitting on it (a settle that exceeded its estimate --
    money that WAS spent) survives its expiry. Clamp both ways and a
    customer who overdrew simply waits two months for the debt to
    evaporate.
    """
    now = now or _now()
    row = conn.execute(
        """
        SELECT COALESCE(SUM(net), 0) AS available FROM (
            SELECT CASE
                     WHEN l.expires_at IS NOT NULL AND l.expires_at <= %s
                     THEN LEAST(SUM(e.delta), 0)
                     ELSE SUM(e.delta)
                   END AS net
            FROM credit_entries e
            LEFT JOIN credit_lots l
                   ON l.id = e.lot_id
                  AND l.account_id IS NOT DISTINCT FROM e.account_id
            WHERE e.account_id IS NOT DISTINCT FROM %s
            GROUP BY e.lot_id, l.expires_at
        ) per_lot
        """,
        (now, account_id),
    ).fetchone()
    return int(row["available"] or 0)


def available(account_id: Optional[int], dsn: Optional[str] = None) -> int:
    """What this account can spend right now, in integer credits.

    Can be NEGATIVE: `settle()` is allowed to overdraw when the actual
    cost beat the estimate, because the money is already spent and
    pretending otherwise is the lie that breaks reconciliation. A
    negative balance is what refuses the next `hold`.
    """
    with db.connect(dsn) as conn:
        return _available(conn, account_id)


def lots(account_id: Optional[int], dsn: Optional[str] = None,
         *, include_expired: bool = True) -> list[dict[str, Any]]:
    """This account's lots, soonest-expiry first -- the order credit is
    consumed in, so the list reads as the burn-down it is."""
    now = _now()
    with db.connect(dsn) as conn:
        rows = conn.execute(
            "SELECT * FROM credit_lots WHERE account_id IS NOT DISTINCT FROM %s "
            "AND (%s OR expires_at IS NULL OR expires_at > %s) "
            "ORDER BY expires_at ASC NULLS LAST, id ASC",
            (account_id, bool(include_expired), now),
        ).fetchall()
        return [dict(r) for r in rows]


def entries(account_id: Optional[int], dsn: Optional[str] = None,
            *, ref: Optional[str] = None) -> list[dict[str, Any]]:
    """The audit trail, oldest first. `ref` narrows it to one hold's
    whole lifecycle -- the hold, its settle or its release."""
    with db.connect(dsn) as conn:
        if ref is None:
            rows = conn.execute(
                "SELECT * FROM credit_entries WHERE account_id IS NOT DISTINCT FROM %s "
                "ORDER BY id ASC", (account_id,)).fetchall()
        else:
            rows = conn.execute(
                "SELECT * FROM credit_entries WHERE account_id IS NOT DISTINCT FROM %s "
                "AND ref = %s ORDER BY id ASC", (account_id, ref)).fetchall()
        return [dict(r) for r in rows]


def outstanding(account_id: Optional[int], dsn: Optional[str] = None) -> int:
    """Credits this account is holding against renders in flight --
    the part of its balance that is committed but not yet consumed."""
    with db.connect(dsn) as conn:
        row = conn.execute(
            """
            SELECT COALESCE(-SUM(h.delta), 0) AS held
            FROM credit_entries h
            WHERE h.account_id IS NOT DISTINCT FROM %s AND h.kind = 'hold'
              AND NOT EXISTS (
                    SELECT 1 FROM credit_entries d
                    WHERE d.account_id IS NOT DISTINCT FROM h.account_id
                      AND d.ref = h.ref AND d.kind IN ('settle', 'release'))
            """,
            (account_id,),
        ).fetchone()
        return int(row["held"] or 0)


def outstanding_everyone(dsn: Optional[str] = None) -> int:
    """Every account's outstanding holds, added up: YOUR LIABILITY.

    The one deliberately installation-wide read in this module, and it
    is in tests/test_tenancy.py::UNSCOPED_ALLOWED with that reason.
    `generative.used_today(everyone=True)` and
    `spend.spent_today_everyone` are its two siblings: a number about
    the installation's own books is not a number about anybody's rows,
    and scoping it to an account would make it a different, useless
    number.
    """
    with db.connect(dsn) as conn:
        row = conn.execute(
            """
            SELECT COALESCE(-SUM(h.delta), 0) AS held
            FROM credit_entries h
            WHERE h.kind = 'hold' AND NOT EXISTS (
                    SELECT 1 FROM credit_entries d
                    WHERE d.ref = h.ref AND d.kind IN ('settle', 'release'))
            """
        ).fetchone()
        return int(row["held"] or 0)


def reconcile(account_id: Optional[int], dsn: Optional[str] = None) -> list[dict[str, Any]]:
    """Per lot: `SUM(delta)` from the entries against the denormalised
    `credit_lots.credits_remaining`, and the drift between them.

    The entries are the truth and `credits_remaining` is a running
    figure kept for the queries that pick lots to spend from. They must
    agree; a test asserts they do after every operation in this module.
    An empty result from a non-empty account means someone wrote a lot
    without its grant entry.
    """
    with db.connect(dsn) as conn:
        rows = conn.execute(
            """
            SELECT l.id, l.kind, l.credits_remaining,
                   COALESCE((SELECT SUM(e.delta) FROM credit_entries e
                             WHERE e.lot_id = l.id
                               AND e.account_id IS NOT DISTINCT FROM l.account_id), 0)
                   AS entry_sum
            FROM credit_lots l
            WHERE l.account_id IS NOT DISTINCT FROM %s
            ORDER BY l.id
            """,
            (account_id,),
        ).fetchall()
        return [{"lot_id": r["id"], "kind": r["kind"],
                 "credits_remaining": int(r["credits_remaining"]),
                 "entry_sum": int(r["entry_sum"]),
                 "drift": int(r["credits_remaining"]) - int(r["entry_sum"])}
                for r in rows]


# --------------------------------------------------------------------------
# the write primitive
# --------------------------------------------------------------------------

def _entry(conn, *, account_id: Optional[int], lot_id: Optional[int], delta: int,
           kind: str, ref: Optional[str], generation_id: Optional[int] = None,
           provider: Optional[str] = None) -> int:
    """One append-only movement, plus the lot's running figure.

    The pair is deliberately inseparable and deliberately in the same
    transaction as its caller: an entry without its
    `credits_remaining` update is a drift `reconcile()` would find
    tomorrow, and an update without its entry is a balance with no audit
    trail behind it.
    """
    if kind not in ENTRY_KINDS:
        raise LedgerError(f"entry kind must be one of {ENTRY_KINDS}, got {kind!r}")
    row = conn.execute(
        "INSERT INTO credit_entries "
        "(account_id, lot_id, delta, kind, ref, generation_id, provider, created_at) "
        "VALUES (%s, %s, %s, %s, %s, %s, %s, %s) RETURNING id",
        (account_id, lot_id, int(delta), kind, ref, generation_id, provider, _now()),
    ).fetchone()
    if lot_id is not None:
        conn.execute(
            "UPDATE credit_lots SET credits_remaining = credits_remaining + %s "
            "WHERE id = %s AND account_id IS NOT DISTINCT FROM %s",
            (int(delta), lot_id, account_id),
        )
    return int(row["id"])


def _debit(conn, *, account_id: Optional[int], amount: int, kind: str, ref: str,
           generation_id: Optional[int] = None, provider: Optional[str] = None,
           overdraft_lot_id: Optional[int] = None) -> None:
    """Take `amount` credits soonest-expiry-first, overdrawing if it does
    not fit. The ordinary consumption order, in one place.

    `hold` does its own allocation because it must refuse rather than
    overdraw and it has already computed the balance under the lock.
    This is the other kind of debit -- `settle`'s adjustment, where the
    money is spent and refusing is not one of the options -- so what
    does not fit lands on `overdraft_lot_id` and the balance goes
    negative. Same order either way, which is the point: a customer
    should not be able to tell where a debit came from by looking at
    which lot it drained.
    """
    now = _now()
    wanted = int(amount)
    rows = conn.execute(
        "SELECT id, credits_remaining FROM credit_lots "
        "WHERE account_id IS NOT DISTINCT FROM %s AND credits_remaining > 0 "
        "AND (expires_at IS NULL OR expires_at > %s) "
        "ORDER BY expires_at ASC NULLS LAST, id ASC",
        (account_id, now),
    ).fetchall()
    for row in rows:
        if wanted <= 0:
            break
        take = min(wanted, int(row["credits_remaining"]))
        _entry(conn, account_id=account_id, lot_id=int(row["id"]), delta=-take,
               kind=kind, ref=ref, generation_id=generation_id, provider=provider)
        wanted -= take
    if wanted > 0:
        _entry(conn, account_id=account_id, lot_id=overdraft_lot_id, delta=-wanted,
               kind=kind, ref=ref, generation_id=generation_id, provider=provider)


