# the lock
# --------------------------------------------------------------------------

def _lock(conn, account_id: Optional[int]) -> None:
    """Serialise every balance-changing operation on ONE account.

    Transaction-scoped, so it releases on commit *or* rollback: a worker
    that dies holding it cannot wedge an account's balance forever,
    which a `FOR UPDATE` on a balance row would also give but only if
    every future writer remembers to take it. Keyed per account, so two
    customers never contend, and the critical section is one SELECT and
    one INSERT.

    COALESCE, and the reason is not cosmetic: `'credit:' || NULL` is
    NULL, and `pg_advisory_xact_lock(NULL)` returns NULL having locked
    NOTHING -- so on the unowned pool (account_id NULL, which is every
    row on a database that has not been seeded) the lock would silently
    not exist and the concurrency test would pass for the wrong reason.
    """
    conn.execute(
        "SELECT pg_advisory_xact_lock(hashtext('credit:' || COALESCE(%s::text, '-')))",
        (account_id,),
    )


