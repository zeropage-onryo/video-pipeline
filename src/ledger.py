# settle / release
# --------------------------------------------------------------------------

def settle(hold_id: int, actual_usd, *, generation_id: Optional[int] = None,
           dsn: Optional[str] = None) -> int:
    """Close a hold at what the render ACTUALLY cost. Returns net credits
    debited (which is `credits_for_usd(actual_usd)`).

    Three cases, and only the third is interesting:

    - actual == estimate: a zero-delta `settle` entry, written anyway,
      because the audit trail must record that the hold was closed and
      must carry `generation_id` -- the link from money to the clip.
    - actual < estimate: the difference goes back, to the lots the hold
      took it from, in REVERSE order of consumption, capped at what each
      one gave. Symmetric with the burn-down, so a refund cannot put
      credit back on a lot that never funded it.
    - actual > estimate: THE DIFFERENCE IS DEBITED ANYWAY, even into a
      negative balance. The money is already spent -- the provider
      submitted, billed, and does not care about this table. Clamping
      here would make the ledger disagree with the invoice, which is the
      one thing it exists not to do, and the NEXT `hold()` is refused
      because `available()` is now negative.

    WHERE THE EXTRA DEBIT LANDS is the part that took a second pass.
    It is an ordinary debit and it is taken in the ordinary order --
    soonest-expiry-first across this account's unexpired lots, exactly
    as `hold` allocates. The first version put it all on the LAST lot
    the hold touched, which is the latest-expiring one, so a render
    that beat its estimate drove the customer's PURCHASED credit
    negative while an already-empty subscription lot sat at zero:
    the debt landed on the credit they still owned rather than on the
    credit they were spending.

    When nothing is left anywhere -- the usual case, since the hold had
    just emptied those lots -- the genuine overdraft has no lot with
    credit to sit on, and it goes on the SOONEST-EXPIRING lot the hold
    drew from. That tie-break is not arbitrary: it is where the
    burn-down was, and `_available` clamps an expired lot from above
    only, so a debt parked there survives the lot's expiry instead of
    evaporating with it.
    """
    debit = credits_for_usd(actual_usd)
    with db.connect(dsn) as conn:
        # The hold's own rows are append-only and immutable, so reading
        # them before the lock is safe; everything that could CHANGE
        # (whether it has already been settled or released, and the
        # entries this settle writes) happens after it.
        account_id, ref, holds = _hold_group(conn, hold_id)
        _lock(conn, account_id)
        already = _resolved(conn, account_id, ref)
        if already == "settle":
            return debit
        if already == "release":
            raise LedgerError(f"hold {hold_id} was already released; it cannot settle")

        held = sum(-int(h["delta"]) for h in holds)
        diff = debit - held
        if diff == 0:
            _entry(conn, account_id=account_id, lot_id=holds[0]["lot_id"], delta=0,
                   kind="settle", ref=ref, generation_id=generation_id,
                   provider=holds[0]["provider"])
        elif diff < 0:
            back = -diff
            for h in reversed(holds):
                if back <= 0:
                    break
                give = min(back, -int(h["delta"]))
                _entry(conn, account_id=account_id, lot_id=h["lot_id"], delta=give,
                       kind="settle", ref=ref, generation_id=generation_id,
                       provider=h["provider"])
                back -= give
        else:
            _debit(conn, account_id=account_id, amount=diff, kind="settle", ref=ref,
                   generation_id=generation_id, provider=holds[0]["provider"],
                   overdraft_lot_id=holds[0]["lot_id"])
        return debit


def release(hold_id: int, reason: str, dsn: Optional[str] = None) -> int:
    """Give the whole hold back. Returns the credits restored.

    A provider error, a timeout, or a QC failure: the customer pays
    nothing and the cost lands in `waste_usd` -- the number that makes
    "we refund failed renders" a real line on your books rather than a
    slogan. Reversed entry by entry rather than as one lump, so each
    lot gets back exactly what it gave and the expiry clock it was
    granted under still governs the credit.

    `reason` is required and is deliberately NOT stored: the entries
    table has no free-text column and should not grow one -- a reason
    field on an append-only money table becomes the place people put
    the thing they should have modelled. It belongs in the caller's log
    and on the hold row the Queue shows. It is still an argument,
    because a release nobody can say the reason for is the one that
    turns out to have been a bug.
    """
    if not reason:
        raise LedgerError("a release needs a reason")
    with db.connect(dsn) as conn:
        account_id, ref, holds = _hold_group(conn, hold_id)
        _lock(conn, account_id)
        already = _resolved(conn, account_id, ref)
        if already == "release":
            return sum(-int(h["delta"]) for h in holds)
        if already == "settle":
            raise LedgerError(f"hold {hold_id} was already settled; it cannot release")
        restored = 0
        for h in holds:
            give = -int(h["delta"])
            _entry(conn, account_id=account_id, lot_id=h["lot_id"], delta=give,
                   kind="release", ref=ref, provider=h["provider"])
            restored += give
        return restored


