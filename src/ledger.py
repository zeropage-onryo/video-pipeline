# account_id is NOT here: db.own_table adds the column and the FOREIGN
# KEY to accounts(id) as its own step, because accounts.SCHEMA lives in
# the module that imports db. Every owned table in the repo is built
# this way.
SCHEMA = """
CREATE TABLE IF NOT EXISTS credit_lots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              TEXT   NOT NULL,
    credits_granted   BIGINT NOT NULL,
    credits_remaining BIGINT NOT NULL,
    granted_at        TEXT   NOT NULL,
    expires_at        TEXT,
    source_ref        TEXT,
    note              TEXT
);

CREATE TABLE IF NOT EXISTS credit_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lot_id        BIGINT,
    delta         BIGINT NOT NULL,
    kind          TEXT   NOT NULL,
    ref           TEXT,
    generation_id BIGINT,
    -- the reaper's other half. The design doc says "hold carries the
    -- provider and the estimate: without them it cannot tell a dead
    -- render from a slow one" -- the ESTIMATE needs no column, it is
    -- the hold's own `delta` in credits, which also keeps the promise
    -- that no float is ever stored on this path.
    provider      TEXT,
    -- The ONE column in this table that is ever written twice, and it is
    -- deliberately not a money field: NULL at hold time, stamped once by
    -- `mark_submitted` in the instant before the provider call. It is
    -- what separates "the render never happened" from "the render was
    -- paid for and nothing recorded it" -- two states that otherwise
    -- look identical to the reaper and have opposite correct answers.
    -- Guarded to go NULL -> timestamp and never back; delta, kind, ref
    -- and lot_id remain immutable, so the append-only rule that matters
    -- (nothing about the MONEY is ever updated) still holds.
    submitted_at  TEXT,
    created_at    TEXT   NOT NULL
);
"""

# Written after own_table, because both name account_id and the column
# does not exist until then.
#
# The lots index is the webhook guard: Stripe delivers at least once, so
# a payment intent replayed an hour later must not grant a second time.
# NULLS NOT DISTINCT (Postgres 15+) is what makes it hold for the
# unowned pool too -- with the default, two grants with a NULL
# account_id and the same source_ref are "different" rows and both land.
#
# The entries index is the belt to `hold`'s braces: the advisory lock is
# what actually makes a retried hold idempotent, and this is what still
# refuses a duplicate if some future caller writes an entry without
# taking it. (account_id, kind, ref, lot_id) rather than
# (account_id, kind, ref) because ONE hold may span several lots.
INDEXES = """
CREATE UNIQUE INDEX IF NOT EXISTS idx_credit_lots_source
    ON credit_lots (account_id, kind, source_ref)
    NULLS NOT DISTINCT
    WHERE source_ref IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_credit_lots_account
    ON credit_lots (account_id, expires_at);
CREATE UNIQUE INDEX IF NOT EXISTS idx_credit_entries_ref
    ON credit_entries (account_id, kind, ref, lot_id)
    NULLS NOT DISTINCT
    WHERE ref IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_credit_entries_account
    ON credit_entries (account_id, lot_id);
"""


def init(dsn: Optional[str] = None) -> None:
    """Create both tables, own them, index them. Safe to run repeatedly.

    `add_nightly_runs_table`'s idempotent shape: every statement is
    CREATE ... IF NOT EXISTS, so the dev server's re-import on save runs
    this a hundred times a day for free. Registered in app/main.py's
    lifespan and in tests/test_tenancy.py::_init_everything -- without
    both, the schema audit never sees these tables and cannot tell you
    they were never decided about.
    """
    with db.connect(dsn) as conn:
        conn.execute(SCHEMA)
        # submitted_at landed a day after the tables did and no database
        # in the world had shipped them yet -- but the dev server had
        # already run init() a hundred times, so the additive ALTER is
        # here for the same reason db.add_legacy_column is: the CREATE
        # above covers a fresh database and this covers the one on the
        # machine you are typing on.
        if "submitted_at" not in db.columns(conn, "credit_entries"):
            conn.execute("ALTER TABLE credit_entries ADD COLUMN submitted_at TEXT")
        db.own_table(conn, "credit_lots")
        db.own_table(conn, "credit_entries")
        conn.execute(INDEXES)


# --------------------------------------------------------------------------
# time
# --------------------------------------------------------------------------

def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _parse(stamp: str) -> datetime:
    dt = datetime.fromisoformat(stamp)
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def _plus_months(stamp: str, months: int) -> str:
    """`granted_at + EXPIRY_MONTHS`, clamping the day.

    Hand-rolled rather than dateutil because nothing else in this repo
    pulls that in for one call, and the only hard case is the one
    everybody gets wrong: the 31st of a month whose successor is
    shorter. 31 December + 2 months is 28 February, not 3 March -- a
    lot must never expire LATER than the month arithmetic says, or an
    account keeps credit it was told it would lose.
    """
    dt = _parse(stamp)
    month_index = dt.month - 1 + months
    year = dt.year + month_index // 12
    month = month_index % 12 + 1
    # the last day of the target month, without calendar.monthrange's import
    next_month = datetime(year + (month == 12), month % 12 + 1, 1, tzinfo=timezone.utc)
    last_day = (next_month - timedelta(days=1)).day
    return dt.replace(year=year, month=month, day=min(dt.day, last_day)).isoformat()


