"""
Pre-production: places you could shoot, and concepts you haven't shot.

Everything else in this pipeline starts from footage that already
exists -- manifest.json is a record of what was filmed. This module
covers the phase before that: photograph the spaces available to you,
have them described, and generate concepts grounded in those real
spaces rather than in a script written blind.

An extension to db.py in its own module, same as generative.py: own
SCHEMA, own init(), run after db.init_db().

`shot_done` is the label worth having. You generate several concepts
and go shoot some of them; that choice is ground truth about what's
actually worth making, in exactly the way ideas.selected is for
pitches, and it costs one column to keep.

Postgres since 2026-09-03, step 3 of docs/tasks/task-postgres-migration.md.
The SQLite-era migration that used to be a third of this file -- the
locations rebuild from UNIQUE(name) to UNIQUE(account_id, name), the
concept_locations FK repair for tables rewritten to `locations_old`,
the dangling-REFERENCES scan, and eight ALTER-if-missing column adds --
is gone (Mike's call): no Postgres database will ever be in the
pre-tenancy shape, so SCHEMA below IS the final shape, every column
inline with the comment that explains it. What those migrations
protected is pinned in tests/test_tenancy.py as properties instead:
two accounts can each own a Garage, one account cannot own two,
ownerless rows still collide, the cascade still fires.
"""
from __future__ import annotations

import json
import re
from typing import Any, Optional

from .db import _hash, _now, connect, own_table

BRANDS = ("antihero", "zeropage")

SCHEMA = """
CREATE TABLE IF NOT EXISTS locations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TEXT    NOT NULL,
    -- Not UNIQUE on its own: two accounts can each own a place called
    -- "Garage". Uniqueness is the expression index below.
    name        TEXT    NOT NULL,
    photo_count INTEGER,
    description_json TEXT,
    notes       TEXT,
    -- Nullable: NULL is the unowned pool (see db.add_account_column,
    -- which also declares the FK to accounts(id)).
    account_id  BIGINT
);

CREATE TABLE IF NOT EXISTS shoot_concepts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TEXT    NOT NULL,
    brand       TEXT    NOT NULL,
    client      TEXT,
    spark       TEXT,
    title       TEXT    NOT NULL,
    hook        TEXT,
    logline     TEXT,
    -- The board's one-line label, separate from `logline` ON PURPOSE
    -- (2026-09-02). scene_brief_prompt.txt makes logline 2-4 sentences
    -- -- "where the IDEA survives", the want/obstacle/turn a one-action
    -- prompt cannot hold. That is the idea record; this is the card.
    -- Trimming the first to make the second threw the idea away.
    card_line   TEXT,
    duration    TEXT,
    shots_json  TEXT    NOT NULL,
    ai_json     TEXT,
    edit_note   TEXT,
    grade_note  TEXT,
    shot_done   INTEGER NOT NULL DEFAULT 0,
    prompt_hash TEXT,
    warnings_json TEXT,
    use_pov     INTEGER NOT NULL DEFAULT 1,
    notes       TEXT,
    -- taste + performance judge scores (BACKLOG #5): a manual,
    -- history-based ranking. Gates nothing.
    judge_overall DOUBLE PRECISION,
    judge_taste   DOUBLE PRECISION,
    judge_perf    DOUBLE PRECISION,
    judge_reason  TEXT,
    -- `format` is the skeleton the concept rides (Zero Page).
    format        TEXT,
    -- Zero Page's on-brand (uncanny) gate: a fixed-rubric pass/fail that
    -- decides whether a concept may auto-post. Separate from the taste
    -- judge above -- this one gates.
    uncanny_overall DOUBLE PRECISION,
    uncanny_passed  INTEGER,
    uncanny_reason  TEXT,
    -- the pick: which of the several scenes one idea produced is worth
    -- rendering (see set_picked / pick_rate). Timestamped so a rate can
    -- be windowed.
    picked_at   TEXT,
    -- the board clears itself: a concept you resolved (picked and sent
    -- to render, or passed over) stops being a card without stopping
    -- being a row. The row is the label -- pick_rate needs the ones you
    -- did NOT pick as much as the ones you did -- and it stays in the
    -- Dev Studio's ungraded pool until it is graded. Archiving is the
    -- board's memory, not the database's.
    archived_at TEXT,
    -- WHY a reason and not just a timestamp (2026-08-31). archived_at
    -- records THAT a concept was passed over; it cannot record what was
    -- wrong with it. Thirteen of the first fifteen concepts were
    -- rejected and the system learned nothing from any of them, because
    -- nothing ever asked. An unpicked row is the ONLY negative signal
    -- this pipeline collects at volume, and a rejection with no reason
    -- can never reach avoid_guidance.
    archive_reason TEXT,
    account_id  BIGINT
);

CREATE TABLE IF NOT EXISTS concept_locations (
    concept_id  BIGINT NOT NULL REFERENCES shoot_concepts(id) ON DELETE CASCADE,
    location_id BIGINT NOT NULL REFERENCES locations(id) ON DELETE CASCADE,
    UNIQUE (concept_id, location_id)
);

CREATE TABLE IF NOT EXISTS scene_briefs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TEXT NOT NULL,
    brand      TEXT NOT NULL,
    spark      TEXT,
    title      TEXT NOT NULL,
    brief      TEXT NOT NULL,
    account_id BIGINT
);

CREATE INDEX IF NOT EXISTS idx_concepts_shot ON shoot_concepts (shot_done);
CREATE INDEX IF NOT EXISTS idx_cl_concept    ON concept_locations (concept_id);
-- the shape every board query uses: this account's, newest first
CREATE INDEX IF NOT EXISTS idx_concepts_account ON shoot_concepts (account_id, id DESC);
"""

# Uniqueness of a location's name is an expression index, not a table
# constraint, and the COALESCE is load-bearing: Postgres, like SQLite,
# treats NULLs as distinct inside a UNIQUE, so a plain
# UNIQUE(account_id, name) lets two ownerless rows named "hallway" both
# exist -- which is exactly what add_location's upsert relies on NOT
# happening. Folding NULL to 0 keeps an unowned row behaving the way it
# did before tenancy, so nothing changes for a caller that has not been
# given an account yet, while two real accounts can still each own a
# Garage. add_location's ON CONFLICT names the same expressions, which
# is how Postgres finds this index.
LOCATIONS_UNIQUE = (
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_locations_owner_name "
    "ON locations (COALESCE(account_id, 0), name)"
)


def init(dsn: Optional[str] = None) -> None:
    """Create the pre-production tables. Run after db.init_db()."""
    with connect(dsn) as conn:
        conn.execute(SCHEMA)
        conn.execute(LOCATIONS_UNIQUE)
        # tenancy: the FK to accounts(id) on each owned table, and the
        # claim of any ownerless rows once there is an account to claim
        # them for (db.own_table)
        own_table(conn, "locations")
        own_table(conn, "shoot_concepts")
        own_table(conn, "scene_briefs")


def save_judge_score(concept_id: int, judge: dict, dsn: Optional[str] = None, *,
                     account_id: int) -> None:
    """Store the taste + performance judge's verdict on a concept so the UI
    can show and rank by it. `judge` is taste_judge.score_concept()'s dict."""
    with connect(dsn) as conn:
        conn.execute(
            "UPDATE shoot_concepts SET judge_overall=%s, judge_taste=%s, "
            "judge_perf=%s, judge_reason=%s WHERE id=%s AND account_id IS NOT DISTINCT FROM %s",
            (judge.get("overall"), judge.get("taste_fit"), judge.get("performance"),
             " · ".join(judge.get("reasons") or [])[:500], concept_id, account_id),
        )


def save_uncanny_score(concept_id: int, score: dict, dsn: Optional[str] = None, *,
                       account_id: int) -> None:
    """Store Zero Page's on-brand gate verdict on a concept so the UI can show
    the PASS/HOLD and autopilot can check it. `score` is
    uncanny_judge.score_concept()'s dict."""
    with connect(dsn) as conn:
        conn.execute(
            "UPDATE shoot_concepts SET uncanny_overall=%s, uncanny_passed=%s, "
            "uncanny_reason=%s WHERE id=%s AND account_id IS NOT DISTINCT FROM %s",
            (score.get("overall"), 1 if score.get("passed") else 0,
             " · ".join(score.get("reasons") or [])[:500], concept_id, account_id),
        )


def delete_concept(concept_id: int, dsn: Optional[str] = None, *,
                   account_id: int) -> None:
    """Discard a concept for good -- if it is yours. concept_locations
    rows cascade via the FK.

    Deleting someone else's is silently a no-op rather than an error,
    for the same reason get_concept returns None: an error would confirm
    the row exists."""
    with connect(dsn) as conn:
        conn.execute(
            "DELETE FROM shoot_concepts WHERE id = %s AND account_id IS NOT DISTINCT FROM %s",
            (concept_id, account_id),
        )


def delete_all_concepts(brand: Optional[str] = None, dsn: Optional[str] = None, *,
                        account_id: int) -> int:
    """Clear ONE ACCOUNT's concept slate -- all of it, or just one of its
    brands. Returns how many were removed. concept_locations cascades.

    `account_id` is required here above all: this used to be
    `DELETE FROM shoot_concepts` with no argument at all, which wiped the
    whole table. With a second account on the database that is not a
    reset, it is someone else's work gone."""
    with connect(dsn) as conn:
        if brand:
            cur = conn.execute(
                "DELETE FROM shoot_concepts WHERE brand = %s AND account_id IS NOT DISTINCT FROM %s",
                (brand, account_id),
            )
        else:
            cur = conn.execute(
                "DELETE FROM shoot_concepts WHERE account_id IS NOT DISTINCT FROM %s", (account_id,)
            )
        return cur.rowcount


