def add_location(
    name: str,
    description: Optional[dict] = None,
    photo_count: Optional[int] = None,
    notes: Optional[str] = None,
    dsn: Optional[str] = None,
    *,
    account_id: int,
) -> int:
    """
    Record (or re-record) a place you can shoot. Keyed by name, so
    re-describing a location after adding photos updates it instead of
    creating a second row -- names are how you refer to a space out
    loud, and two rows for one hallway would be a bug, not a feature.
    """
    if not name or not name.strip():
        raise ValueError("a location needs a name")
    name = name.strip()

    with connect(dsn) as conn:
        # RETURNING id is right on both paths of the upsert -- the row
        # inserted, or the row DO UPDATE touched -- which lastrowid never
        # was. The conflict target has to spell out the expressions of
        # LOCATIONS_UNIQUE for Postgres to pick that index.
        row = conn.execute(
            """
            INSERT INTO locations (created_at, name, photo_count, description_json,
                                   notes, account_id)
            VALUES (%s, %s, %s, %s, %s, %s)
            ON CONFLICT ((COALESCE(account_id, 0)), name) DO UPDATE SET
                photo_count      = excluded.photo_count,
                description_json = excluded.description_json,
                notes            = COALESCE(excluded.notes, locations.notes)
            RETURNING id
            """,
            (_now(), name, photo_count,
             json.dumps(description) if description is not None else None, notes,
             account_id),
        ).fetchone()
        return int(row["id"])


def _location_row(row) -> dict[str, Any]:
    data = dict(row)
    raw = data.pop("description_json", None)
    data["description"] = json.loads(raw) if raw else None
    return data


def get_location(location_id: int, dsn: Optional[str] = None, *,
                 account_id: int) -> Optional[dict[str, Any]]:
    with connect(dsn) as conn:
        row = conn.execute(
            "SELECT * FROM locations WHERE id = %s AND account_id IS NOT DISTINCT FROM %s",
            (location_id, account_id),
        ).fetchone()
    return _location_row(row) if row else None


def get_location_by_name(name: str, dsn: Optional[str] = None, *,
                         account_id: int) -> Optional[dict[str, Any]]:
    with connect(dsn) as conn:
        row = conn.execute(
            "SELECT * FROM locations WHERE name = %s AND account_id IS NOT DISTINCT FROM %s",
            (name, account_id),
        ).fetchone()
    return _location_row(row) if row else None


def list_locations(dsn: Optional[str] = None, *,
                   account_id: int) -> list[dict[str, Any]]:
    with connect(dsn) as conn:
        return [
            _location_row(r)
            for r in conn.execute(
                "SELECT * FROM locations WHERE account_id IS NOT DISTINCT FROM %s ORDER BY name ASC",
                (account_id,),
            )
        ]


